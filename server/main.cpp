std::string executeCommand(const std::vector<std::string>& args) {//this command takes the arguments as parameters and returns the output to be displayed in client as string
    std::string name = args[0]; // Parser guarantees at least one element.
    
    for (char& ch : name) {//convert the command into UPPER case
        if (ch >= 'a' && ch <= 'z') ch = static_cast<char>(ch - 'a' + 'A');
    }

    if (name == "PING") {
        if (args.size() == 1) return resp::simple("PONG"); 
        if (args.size() == 2) return resp::bulk(args[1]);
        return resp::error("ERR wrong number of arguments for PING");
    }
    if (name == "ECHO") {
        if (args.size() == 2) return resp::bulk(args[1]);
        return resp::error("ERR wrong number of arguments for ECHO");
    }
    return resp::error("ERR unknown command");
}

void handleClient(int fd) {
    net::Socket connection(fd); //creates a new Socket object called connection using this socket fd-->this connection object now owns the fd and fd's life cycle is tied to scope of connection
   
    try {//put the client handlin code in a try block-->potentially memory alocation issues etc are possible
        
        /*
        We will initalise the persistent recieve buffer for this clinet-->input. 
        We will store all the incoming bytes in this string only
        hence it is initalised outside the while loop
        */
        std::string input;
        while (true) {

            /*
            Here we can see that we first parse before even recieving--this i sjust in case ot clear the bufferif anyhting already exists
            */
            auto result = resp::parseCommand(input);

            //if after parsing there is an error then we send the appropriate error response and return the function
            if (result.status == resp::Status::Error) {
                net::sendAll(fd, resp::error("ERR Protocol error: " + result.error));
                return; // Socket destructor closes the connection.
            }
            
            //if after parsing the command is parsed completed then the status is complete-->hence we will execute the command
            if (result.status == resp::Status::Complete) {
                if (!net::sendAll(fd, executeCommand(result.arguments))) return; //send the result string for the command generated by executeCommand to cline using sendAll, if ny error in this send then return immediately
                input.erase(0, result.consumed); //remove the parsed and executed command from the inout string buffer
                continue; // Process another buffered command before receiving.
            }
            
            //If the parser status returns incomplete we reach here
            const ssize_t n = net::receiveMore(fd, input); //recieve bytes from the client, in the next iteration if full command recieve it will parse else again we will recieve more bytes
            if (n < 0) { //if any error in recieving the bytes we log the error and return immediately
                std::perror("recv"); 
                return; 
            }

            if (n == 0) { //if n=0 it means the client closed-hence we log that and return
                if (!input.empty()) std::cerr << "Client closed during a command\n";
                return;
            }
        }
    } 
    catch (const std::exception& e) {//catches any excpetion and prints the exception
        std::cerr << "Client handler failed: " << e.what() << '\n';
    }
}

int main() {
    net::Socket listener(::socket(AF_INET, SOCK_STREAM, 0)); //sets up the listening socket
    if (listener.get() < 0) { 
        std::perror("socket"); 
        return 1; 
    }
    
    /*
    Here we are configuring the reuse of the same port for the socket
    For example if we stop the server and immediately restart it the during binding we might get an error sayin Address already in use
    This allows us to reuse the same address for this socket
    why &reuse is passed? --> for the parameter the setsockopt takes a pointer to the memory containing the option value
    So we are effectively saying-->Here is the address of a 4-byte integer containing 1. Use it to enable SO_REUSEADDR on this socket.
    */
    int reuse = 1;
    if (::setsockopt(listener.get(), SOL_SOCKET, SO_REUSEADDR, &reuse, sizeof(reuse)) < 0) {
        std::perror("setsockopt"); 
        return 1;
    }

    //configure the address
    sockaddr_in address{}; //initalise the sockaddr_in struct
    address.sin_family = AF_INET; //for IPv4 address
    address.sin_port = htons(net::Port); //sets the correct port no(6739) after converting to big endian
    address.sin_addr.s_addr = htonl(INADDR_LOOPBACK); //here we are setting the IP address it should bind to-->INADDR_LOOPBACK refers to 127.0.0.1 which means current deivce Ip address
    if (::bind(listener.get(), reinterpret_cast<sockaddr*>(&address),sizeof(address)) < 0) { //bind the socket with the address
        std::perror("bind"); 
        return 1;
    }

    //start the listening-->upto 16 that can wait in queueu to be accepted(doesnt mean ony 16 connetions at a time)
    if (::listen(listener.get(), 16) < 0) { 
        std::perror("listen"); 
        return 1; 
    }


    std::cout << "Listening on 127.0.0.1:" << net::Port << std::endl;
    while (true) {
        const int fd = ::accept(listener.get(), nullptr, nullptr); //when a client connection is available accept the connection and save the socket's fd
        if (fd < 0) {//check if there is an error in the connection socket
            if (errno == EINTR) continue; //if the error is because of an SIGNAL interrupting the accept syscall then we can retry -->hence we just continue(start a new iteration of loop and try to accespt the connection again)
            
            //if any other error then log the error and terminate the main()
            std::perror("accept"); 
            return 1;
        }

        //create a new worker thread for each of the new connections and pass it to handleClient
        try {
            std::thread worker(handleClient, fd);
            worker.detach(); //detach the worker thread so we dont need to manually join the thread
        } 
        
        //if error in creating the wokrer thread then close the connection to the 
        catch (const std::exception& e) {
            ::close(fd);
            std::cerr << "Cannot start client thread: " << e.what() << '\n';
        }
    }
}
